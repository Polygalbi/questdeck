create or replace function public.refresh_questdeck_workspace_member_count()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.questdeck_workspaces workspace
  set member_count = (
    select count(*) from public.questdeck_workspace_memberships membership
    where membership.workspace_id = workspace.id
  )
  where workspace.id in (coalesce(new.workspace_id, old.workspace_id), coalesce(old.workspace_id, new.workspace_id));
  return coalesce(new, old);
end
$$;

drop trigger if exists questdeck_workspace_member_count_trigger on public.questdeck_workspace_memberships;
create trigger questdeck_workspace_member_count_trigger
after insert or update or delete on public.questdeck_workspace_memberships
for each row execute function public.refresh_questdeck_workspace_member_count();

update public.questdeck_workspaces workspace
set member_count = (
  select count(*) from public.questdeck_workspace_memberships membership
  where membership.workspace_id = workspace.id
);

-- New images use workspace_id/user_id/file. Legacy images belong to the
-- original primary workspace and remain available to its members.
drop policy if exists "Active members can view document images" on storage.objects;
drop policy if exists "Active members can upload document images" on storage.objects;
drop policy if exists "Active members can update document images" on storage.objects;
drop policy if exists "Active members can delete document images" on storage.objects;

create policy "Workspace members can view document images"
on storage.objects for select to authenticated
using (
  bucket_id = 'questdeck-document-images'
  and (
    public.has_questdeck_workspace_access((storage.foldername(name))[1])
    or ((storage.foldername(name))[1] = auth.uid()::text and public.is_questdeck_member())
  )
);

create policy "Workspace members can upload document images"
on storage.objects for insert to authenticated
with check (
  bucket_id = 'questdeck-document-images'
  and public.has_questdeck_workspace_access((storage.foldername(name))[1])
  and (storage.foldername(name))[2] = auth.uid()::text
);

create policy "Workspace members can update own document images"
on storage.objects for update to authenticated
using (
  bucket_id = 'questdeck-document-images'
  and public.has_questdeck_workspace_access((storage.foldername(name))[1])
  and (storage.foldername(name))[2] = auth.uid()::text
)
with check (
  bucket_id = 'questdeck-document-images'
  and public.has_questdeck_workspace_access((storage.foldername(name))[1])
  and (storage.foldername(name))[2] = auth.uid()::text
);

create policy "Workspace members can delete own document images"
on storage.objects for delete to authenticated
using (
  bucket_id = 'questdeck-document-images'
  and public.has_questdeck_workspace_access((storage.foldername(name))[1])
  and (storage.foldername(name))[2] = auth.uid()::text
);
