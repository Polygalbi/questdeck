create or replace function public.questdeck_current_member_id()
returns bigint
language sql
stable
security definer
set search_path = public
as $$
  select id from public.questdeck_members
  where lower(email) = lower(coalesce(auth.jwt() ->> 'email', ''))
    and status::text = 'Active'
  limit 1
$$;

create or replace function public.has_questdeck_workspace_access(target_workspace_id text)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.questdeck_workspace_memberships membership
    where membership.workspace_id = target_workspace_id
      and membership.member_id = public.questdeck_current_member_id()
  )
$$;

create or replace function public.is_questdeck_owner()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.questdeck_workspace_memberships membership
    where membership.member_id = public.questdeck_current_member_id()
      and membership.role = 'Owner'
  )
$$;

create or replace function public.is_questdeck_member()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.questdeck_current_member_id() is not null
    and exists (
      select 1 from public.questdeck_workspace_memberships membership
      where membership.member_id = public.questdeck_current_member_id()
    )
$$;

create or replace function public.can_edit_questdeck_workspace(target_workspace_id text)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.questdeck_workspace_memberships membership
    join public.questdeck_role_permissions permissions on permissions.role::text = membership.role
    where membership.member_id = public.questdeck_current_member_id()
      and membership.workspace_id = target_workspace_id
      and permissions.edit_cards
  )
$$;

revoke all on function public.questdeck_current_member_id() from public;
revoke all on function public.has_questdeck_workspace_access(text) from public;
revoke all on function public.is_questdeck_owner() from public;
revoke all on function public.is_questdeck_member() from public;
revoke all on function public.can_edit_questdeck_workspace(text) from public;
grant execute on function public.questdeck_current_member_id() to authenticated;
grant execute on function public.has_questdeck_workspace_access(text) to authenticated;
grant execute on function public.is_questdeck_owner() to authenticated;
grant execute on function public.is_questdeck_member() to authenticated;
grant execute on function public.can_edit_questdeck_workspace(text) to authenticated;

do $$
declare
  table_name text;
  policy record;
begin
  foreach table_name in array array[
    'questdeck_projects', 'questdeck_cards', 'questdeck_subtasks', 'questdeck_disciplines',
    'questdeck_documents', 'questdeck_document_comments', 'questdeck_milestones',
    'questdeck_activity_events', 'questdeck_notifications'
  ]
  loop
    for policy in select policyname from pg_policies where schemaname = 'public' and tablename = table_name
    loop
      execute format('drop policy %I on public.%I', policy.policyname, table_name);
    end loop;
    execute format(
      'create policy %I on public.%I for select to authenticated using (public.has_questdeck_workspace_access(workspace_id))',
      table_name || '_workspace_read', table_name
    );
  end loop;
end
$$;

do $$
declare policy record;
begin
  for policy in select policyname from pg_policies where schemaname = 'public' and tablename = 'questdeck_workspaces'
  loop execute format('drop policy %I on public.questdeck_workspaces', policy.policyname); end loop;
  for policy in select policyname from pg_policies where schemaname = 'public' and tablename = 'questdeck_members'
  loop execute format('drop policy %I on public.questdeck_members', policy.policyname); end loop;
  for policy in select policyname from pg_policies where schemaname = 'public' and tablename = 'questdeck_workspace_memberships'
  loop execute format('drop policy %I on public.questdeck_workspace_memberships', policy.policyname); end loop;
end
$$;

