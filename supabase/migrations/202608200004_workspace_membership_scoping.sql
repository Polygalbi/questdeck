-- Give every Questdeck workspace a real access boundary.
-- Existing production data remains in the oldest active workspace so the
-- migration is lossless, while owners retain access to every workspace.

create table if not exists public.questdeck_workspace_memberships (
  id bigint generated by default as identity primary key,
  workspace_id text not null references public.questdeck_workspaces(id) on delete cascade,
  member_id bigint not null references public.questdeck_members(id) on delete cascade,
  role text not null default 'Member' check (role in ('Owner', 'Admin', 'Team Leader', 'Member', 'Guest')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (workspace_id, member_id)
);

create index if not exists questdeck_workspace_memberships_member_idx
  on public.questdeck_workspace_memberships (member_id, workspace_id);

alter table public.questdeck_role_permissions
  drop constraint if exists questdeck_role_permissions_role_check;
alter table public.questdeck_role_permissions
  add constraint questdeck_role_permissions_role_check
  check (role in ('Owner', 'Admin', 'Team Leader', 'Member', 'Guest'));

insert into public.questdeck_role_permissions (
  role, view_projects, edit_cards, manage_members, workspace_settings, billing_security
)
values ('Team Leader', true, true, false, true, false)
on conflict (role) do update set
  view_projects = excluded.view_projects,
  edit_cards = excluded.edit_cards,
  manage_members = excluded.manage_members,
  workspace_settings = excluded.workspace_settings,
  billing_security = excluded.billing_security;

do $$
declare
  primary_workspace text;
begin
  select id into primary_workspace
  from public.questdeck_workspaces
  order by (status::text = 'Active') desc, created_at asc, id asc
  limit 1;

  if primary_workspace is null then
    insert into public.questdeck_workspaces (id, name, initials, member_count, status)
    values ('workspace', 'Workspace', 'W', 1, 'Active')
    returning id into primary_workspace;
  end if;

  insert into public.questdeck_workspace_memberships (workspace_id, member_id, role)
  select workspace.id, member.id, 'Owner'
  from public.questdeck_workspaces workspace
  cross join public.questdeck_members member
  where member.role::text = 'Owner'
  on conflict (workspace_id, member_id) do update set role = 'Owner', updated_at = now();

  insert into public.questdeck_workspace_memberships (workspace_id, member_id, role)
  select primary_workspace, member.id,
    case when member.role::text in ('Owner', 'Admin', 'Team Leader', 'Member', 'Guest')
      then member.role::text else 'Member' end
  from public.questdeck_members member
  where member.role::text <> 'Owner'
  on conflict (workspace_id, member_id) do nothing;

  alter table public.questdeck_projects add column if not exists workspace_id text references public.questdeck_workspaces(id) on delete cascade;
  alter table public.questdeck_cards add column if not exists workspace_id text references public.questdeck_workspaces(id) on delete cascade;
  alter table public.questdeck_subtasks add column if not exists workspace_id text references public.questdeck_workspaces(id) on delete cascade;
  alter table public.questdeck_disciplines add column if not exists workspace_id text references public.questdeck_workspaces(id) on delete cascade;
  alter table public.questdeck_documents add column if not exists workspace_id text references public.questdeck_workspaces(id) on delete cascade;
  alter table public.questdeck_document_comments add column if not exists workspace_id text references public.questdeck_workspaces(id) on delete cascade;
  alter table public.questdeck_milestones add column if not exists workspace_id text references public.questdeck_workspaces(id) on delete cascade;
  alter table public.questdeck_activity_events add column if not exists workspace_id text references public.questdeck_workspaces(id) on delete cascade;
  alter table public.questdeck_notifications add column if not exists workspace_id text references public.questdeck_workspaces(id) on delete cascade;

  update public.questdeck_projects set workspace_id = primary_workspace where workspace_id is null;
  update public.questdeck_cards card set workspace_id = coalesce(project.workspace_id, primary_workspace)
    from public.questdeck_projects project where card.project_id = project.id and card.workspace_id is null;
  update public.questdeck_cards set workspace_id = primary_workspace where workspace_id is null;
  update public.questdeck_subtasks task set workspace_id = coalesce(card.workspace_id, primary_workspace)
    from public.questdeck_cards card where task.card_id = card.id and task.workspace_id is null;
  update public.questdeck_subtasks set workspace_id = primary_workspace where workspace_id is null;
  update public.questdeck_disciplines set workspace_id = primary_workspace where workspace_id is null;
  update public.questdeck_documents set workspace_id = primary_workspace where workspace_id is null;
  update public.questdeck_document_comments comment set workspace_id = coalesce(document.workspace_id, primary_workspace)
    from public.questdeck_documents document where comment.document_id = document.id and comment.workspace_id is null;
  update public.questdeck_document_comments set workspace_id = primary_workspace where workspace_id is null;
  update public.questdeck_milestones set workspace_id = primary_workspace where workspace_id is null;
  update public.questdeck_activity_events set workspace_id = primary_workspace where workspace_id is null;
  update public.questdeck_notifications set workspace_id = primary_workspace where workspace_id is null;

  alter table public.questdeck_projects alter column workspace_id set not null;
  alter table public.questdeck_cards alter column workspace_id set not null;
  alter table public.questdeck_subtasks alter column workspace_id set not null;
  alter table public.questdeck_disciplines alter column workspace_id set not null;
  alter table public.questdeck_documents alter column workspace_id set not null;
  alter table public.questdeck_document_comments alter column workspace_id set not null;
  alter table public.questdeck_milestones alter column workspace_id set not null;
  alter table public.questdeck_activity_events alter column workspace_id set not null;
  alter table public.questdeck_notifications alter column workspace_id set not null;
end
$$;

