do $$
declare
  constraint_name text;
  target_table text;
begin
  foreach target_table in array array['questdeck_projects', 'questdeck_disciplines']
  loop
    for constraint_name in
      select constraint_record.conname
      from pg_constraint constraint_record
      join pg_attribute attribute_record
        on attribute_record.attrelid = constraint_record.conrelid
       and attribute_record.attnum = any(constraint_record.conkey)
      where constraint_record.conrelid = ('public.' || target_table)::regclass
        and constraint_record.contype = 'u'
      group by constraint_record.conname, constraint_record.conkey
      having count(*) = 1 and max(attribute_record.attname) = 'name'
    loop
      execute format('alter table public.%I drop constraint %I', target_table, constraint_name);
    end loop;
  end loop;
end
$$;

